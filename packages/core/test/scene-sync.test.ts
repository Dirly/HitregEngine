import { describe, expect, it } from "vitest";
import {
  ComponentRegistry,
  applyOps,
  changedProps,
  ownerConflicts,
  ownerHeld,
  recordProps,
  createScene,
  duplicateAddIds,
  entityEditsOf,
  idCounter,
  ownerOverridesSchema,
  planSceneSync,
  recordOwnerEdit,
  registerCoreComponents,
  stableId,
  targetFromOps,
  type Op,
  type SceneDoc,
} from "../src/index.js";

const reg = new ComponentRegistry();
registerCoreComponents(reg);
const tf = (p: number[], s = 1) => ({ position: p, rotation: [0, 0, 0, 1], scale: [s, s, s] });
const prop = (id: string, prefabId: string, p: number[], parent: string | null = "room"): Op => ({
  op: "add-entity",
  id,
  entity: { name: prefabId.split("/").pop()!, parent, tags: ["static"], components: { transform: tf(p), prefab: { prefabId, props: {}, overrides: [] } } },
});
const light = (id: string, p: number[], intensity: number): Op => ({
  op: "add-entity",
  id,
  entity: { name: "lamp light", parent: "room", tags: [], components: { transform: tf(p), light: { kind: "point", color: "#ffaa55", intensity, range: 8 } } },
});
const room: Op = { op: "add-entity", id: "room", entity: { name: "room", parent: null, tags: [], components: { transform: tf([0, 0, 0]) } } };

/** What a builder generates: a room, three props, one light. */
const build = (over: { crateAt?: number[]; extra?: boolean; intensity?: number } = {}): Op[] => [
  room,
  prop("room--crate-1", "props/crate", over.crateAt ?? [1, 0, 1]),
  prop("room--barrel-1", "props/barrel", [3, 0, 1]),
  prop("room--barrel-2", "props/barrel", [5, 0, 1]),
  light("room--lamp", [0, 3, 0], over.intensity ?? 4),
  ...(over.extra ? [prop("room--crate-2", "props/crate", [7, 0, 1])] : []),
];
const target = (ops: Op[]) => targetFromOps("s", ops, reg);
const sync = (live: SceneDoc, ops: Op[], edits?: unknown, claim?: (id: string) => boolean) =>
  planSceneSync(live, target(ops), { builder: "b", edits: edits ? ownerOverridesSchema.parse(edits) : null, claim, registry: reg });
const run = (live: SceneDoc, ops: Op[], edits?: unknown) => {
  const p = sync(live, ops, edits);
  return { plan: p, doc: applyOps(live, p.ops, reg).doc };
};
/** A live scene the builder has synced once, plus an entity nobody generates. */
function seeded(): SceneDoc {
  let doc = run(createScene("s"), build()).doc;
  doc = applyOps(doc, [prop("hand-rug", "props/rug", [2, 0, 2])], reg).doc;
  return doc;
}

describe("stable ids", () => {
  it("are built from what a thing is and its key, per scope", () => {
    expect(stableId("camp", "floor-5", "tent", 1)).toBe("camp--floor-5--tent-1");
    expect(stableId("Gut", "Fire: mesa mid")).toBe("gut--fire-mesa-mid");
    const ids = idCounter();
    expect([ids.of("camp", "tent"), ids.of("camp", "tent"), ids.of("hall", "tent")]).toEqual(["camp--tent-1", "camp--tent-2", "hall--tent-1"]);
  });
  it("a duplicate id fails loudly, naming every one", () => {
    const ops = [...build(), prop("room--crate-1", "props/crate", [9, 0, 9]), prop("room--lamp", "props/crate", [9, 0, 9])];
    expect(duplicateAddIds(ops)).toEqual(["room--crate-1", "room--lamp"]);
    expect(() => target(ops)).toThrow(/2 duplicate id\(s\).*room--crate-1, room--lamp/);
  });
});

describe("planSceneSync", () => {
  it("first sync adds everything with the builder tag; a re-run is zero ops", () => {
    const { plan, doc } = run(createScene("s"), build());
    expect(plan.counts.add).toBe(5);
    expect(doc.entities["room--crate-1"]!.tags).toContain("built:b");
    expect(sync(doc, build()).ops).toEqual([]);
  });

  it("a one-prop change is one op, and an entity nobody generates is never touched", () => {
    const live = seeded();
    const { plan, doc } = run(live, build({ crateAt: [1.5, 0, 1] }));
    expect(plan.ops).toHaveLength(1);
    expect(plan.ops[0]).toMatchObject({ op: "set-component", id: "room--crate-1", component: "transform" });
    expect(doc.entities["hand-rug"]).toEqual(live.entities["hand-rug"]);
    const more = run(doc, build({ crateAt: [1.5, 0, 1], extra: true }));
    expect(more.plan.ops.map((o) => o.op)).toEqual(["add-entity"]);
    const less = run(more.doc, build({ crateAt: [1.5, 0, 1] }));
    expect(less.plan.ops).toEqual([{ op: "remove-entity", id: "room--crate-2" }]);
  });

  it("several builders share a scene; a target id another builder generates is an error", () => {
    let live = seeded();
    const other: Op[] = [prop("mob--1", "mobs/ogre", [0, 0, 5])];
    live = applyOps(live, planSceneSync(live, target(other), { builder: "enc" }).ops, reg).doc;
    expect(live.entities["mob--1"]!.tags).toContain("built:enc");
    expect(sync(live, build()).ops).toEqual([]); // b does not see enc's mob
    expect(() => planSceneSync(live, target(other), { builder: "b" })).toThrow(/generated by another builder: mob--1 \(built:enc\)/);
  });

  it("keeps the record: moved, deleted, a light's colour; and a builder change to other fields still flows", () => {
    const live = seeded();
    const edits = {
      scene: "s",
      frame: "scene",
      overrides: [
        { item: "room--crate-1", builder: "b", set: { pos: [1, 0.5, 1], yaw: 0, scale: 1, prop: "props/crate" }, from: { pos: [1, 0, 1], yaw: 0, scale: 1, prop: "props/crate" }, by: "owner" },
        { item: "room--barrel-2", builder: "b", deleted: true, from: { pos: [5, 0, 1], prop: "props/barrel" } },
        { item: "room--lamp", builder: "b", set: { pos: [0, 3, 0], yaw: 0, scale: 1, components: { light: { kind: "point", color: "#3366ff", intensity: 4, range: 8 } } }, by: "agent" },
      ],
    };
    // the owner's state is already live (he made it in the editor)
    const ownerLive = applyOps(live, [
      { op: "set-component", id: "room--crate-1", component: "transform", data: tf([1, 0.5, 1]) },
      { op: "remove-entity", id: "room--barrel-2" },
      { op: "set-component", id: "room--lamp", component: "light", data: { kind: "point", color: "#3366ff", intensity: 4, range: 8 } },
    ], reg).doc;
    const p = sync(ownerLive, build(), edits);
    expect(p.ops).toEqual([]);
    expect(p.edits.held.map((h) => [h.id, h.by])).toEqual([["room--crate-1", "owner"], ["room--lamp", "agent"]]);
    expect(p.edits.deleted).toEqual(["room--barrel-2"]);
    // the builder now changes the lamp's intensity: the record holds the whole light component, so the colour AND
    // the recorded intensity stay; moving the crate in the builder changes nothing either
    const p2 = sync(ownerLive, build({ intensity: 9, crateAt: [1.2, 0, 1] }), edits);
    expect(p2.ops).toEqual([]);
  });

  it("restores a hand-added entity a whole-file rewrite lost", () => {
    const live = run(createScene("s"), build()).doc;
    const edits = { scene: "s", frame: "scene", overrides: [{ item: "lamp-x", entity: "lamp-x", added: true, parent: "room", name: "my light", set: { pos: [4, 2, 4], yaw: 0, scale: 1, components: { light: { kind: "point", color: "#ffffff", intensity: 2, range: 5 } } } }] };
    const { plan, doc } = run(live, build(), edits);
    expect(plan.edits.restored).toEqual(["lamp-x"]);
    expect(doc.entities["lamp-x"]).toMatchObject({ name: "my light", parent: "room" });
    expect((doc.entities["lamp-x"]!.components["light"] as { intensity: number }).intensity).toBe(2);
    expect(sync(doc, build(), edits).ops).toEqual([]);
  });

  it("matches an old counter-id record by kind + place; reports what matches nothing; refuses to guess", () => {
    const live = seeded();
    const edits = {
      scene: "s",
      frame: "scene",
      overrides: [
        { item: "crate-17", set: { pos: [1, 0.4, 1], yaw: 0, scale: 1, prop: "props/crate" }, from: { pos: [1.3, 0, 1], yaw: 0, scale: 1, prop: "props/crate" } },
        { item: "light-40", name: "lamp light", kind: ["light", "transform"], deleted: true, from: { pos: [0, 3, 0.4], components: {} } },
        { item: "crate-99", builder: "b", set: { pos: [0, 0, 0], prop: "props/crate" }, from: { pos: [40, 0, 40], prop: "props/crate" } },
        { item: "barrel-5", builder: "b", deleted: true, from: { pos: [4, 0, 1], prop: "props/barrel" } },
      ],
    };
    const p = sync(live, build(), edits);
    expect(p.edits.byPlace.map((m) => [m.record, m.entity])).toEqual([["crate-17", "room--crate-1"], ["light-40", "room--lamp"]]);
    expect(p.edits.deleted).toEqual(["room--lamp"]);
    expect(p.edits.stale.map((s) => s.record)).toEqual(["crate-99", "barrel-5"]);
    expect(p.edits.stale[1]!.why).toMatch(/ambiguous/);
    const doc = applyOps(live, p.ops, reg).doc;
    expect((doc.entities["room--crate-1"]!.components["transform"] as { position: number[] }).position).toEqual([1, 0.4, 1]);
    expect(doc.entities["room--lamp"]).toBeUndefined();
  });

  it("moving off counter ids: claims the untagged old entities, warns about the churn once", () => {
    const old: Op[] = [room, ...build().slice(1).map((o, i) => ({ ...o, id: `thing-${i + 10}` }) as Op)];
    old.push(prop("thing-20", "props/barrel", [9, 0, 1]), prop("thing-21", "props/barrel", [11, 0, 1]), prop("thing-22", "props/barrel", [13, 0, 1]));
    const legacy = applyOps(createScene("s"), old, reg).doc; // written by a whole-file rewrite: no built: tags
    const now: Op[] = [...build(), prop("room--barrel-3", "props/barrel", [9, 0, 1]), prop("room--barrel-4", "props/barrel", [11, 0, 1]), prop("room--barrel-5", "props/barrel", [13, 0, 1])];
    const p = sync(legacy, now, undefined, (id) => id.startsWith("thing-") || id === "room");
    expect(p.counts.claimed).toBe(7);
    expect(p.counts.adopted).toBe(1); // room: same id
    expect(p.warnings.join()).toMatch(/id churn: 7 of 8.*running number/);
    const doc = applyOps(legacy, p.ops, reg).doc;
    expect(Object.keys(doc.entities).filter((id) => id.startsWith("thing-"))).toEqual([]);
    expect(sync(doc, now).warnings).toEqual([]);
  });

  it("a stage attaches a component + tag to another builder's entity; that builder's re-sync keeps them; detaching takes them back", () => {
    const live = seeded();
    const script = { name: "portal", params: { mode: "trigger" } };
    const att = (on: boolean) => planSceneSync(live2, target([]), { builder: "portals", registry: reg, attach: on ? [{ id: "room--crate-1", components: { script }, tags: ["portal"] }] : [] });
    let live2 = live;
    let p = att(true);
    expect(p.counts.attached).toBe(1);
    live2 = applyOps(live2, p.ops, reg).doc;
    const e = live2.entities["room--crate-1"]!;
    expect(e.tags).toEqual(expect.arrayContaining(["portal", "attach:portals/script", "attach:portals#portal", "built:b"]));
    expect(att(true).ops).toEqual([]); // idempotent
    expect(sync(live2, build()).ops).toEqual([]); // b regenerates its crate and keeps the stage's script and tag
    p = att(false);
    live2 = applyOps(live2, p.ops, reg).doc;
    expect(live2.entities["room--crate-1"]!.components["script"]).toBeUndefined();
    expect(live2.entities["room--crate-1"]!.tags).toEqual(live.entities["room--crate-1"]!.tags);
  });

  it("never cascades a removal over an entity nobody generates", () => {
    const live = applyOps(seeded(), [prop("hand-pot", "props/pot", [0, 1, 0], "room--crate-1")], reg).doc;
    const p = sync(live, build().filter((o) => (o as { id: string }).id !== "room--crate-1"));
    expect(p.ops.some((o) => o.op === "remove-entity")).toBe(false);
    expect(p.warnings.join()).toMatch(/kept room--crate-1: .*hand-pot/);
  });
});

describe("precedence: owner > agent > generator", () => {
  const T0 = { pos: [1, 0, 1] as [number, number, number], yaw: 0, scale: 1, prop: "props/crate", components: { light: { intensity: 4 } } };
  it("names what an edit changes and what the owner holds", () => {
    expect(changedProps(T0, { ...T0, pos: [1, 0, 2], components: { light: { intensity: 9 } } })).toEqual(["pos", "component:light"]);
    expect(changedProps(T0, null)).toEqual(["*"]);
    expect(recordProps({ set: { ...T0, pos: [1, 0, 2] }, from: T0, added: false, deleted: false })).toEqual(["pos"]);
    expect(recordProps({ set: {}, from: T0, added: false, deleted: true })).toEqual(["*"]);
  });
  it("the owner holds what he set; an agent keeps off it unless it overrides on purpose; his next edit holds again", () => {
    let f = ownerOverridesSchema.parse({ scene: "s", frame: "scene" });
    f = recordOwnerEdit(f, { item: "c", before: T0, after: { ...T0, pos: [1, 0, 2] } }, "t1", "owner");
    let r = f.overrides[0]!;
    expect([r.by, r.ownerProps]).toEqual(["owner", ["pos"]]);
    // an agent turning it touches nothing he set
    const turned = { ...T0, pos: [1, 0, 2] as [number, number, number], yaw: 90 };
    expect(ownerConflicts(r, r.set, turned)).toEqual([]);
    f = recordOwnerEdit(f, { item: "c", before: r.set, after: turned }, "t2", "agent");
    r = f.overrides[0]!;
    expect([r.by, r.ownerProps, r.set.yaw]).toEqual(["agent", ["pos"], 90]);
    // an agent moving it does: a conflict, recorded as an override only when the agent says so
    const moved = { ...turned, pos: [5, 0, 5] as [number, number, number] };
    expect(ownerConflicts(r, turned, moved)).toEqual(["pos"]);
    f = recordOwnerEdit(f, { item: "c", before: turned, after: moved, overrideOwner: ["pos"], note: "pin-12" }, "t3", "agent");
    r = f.overrides[0]!;
    expect([r.ownerProps, r.overrodeOwner, r.note]).toEqual([undefined, ["pos"], "pin-12"]);
    // he moves it again: his again
    f = recordOwnerEdit(f, { item: "c", before: moved, after: { ...moved, pos: [0, 0, 0] } }, "t4", "owner");
    r = f.overrides[0]!;
    expect([r.by, r.ownerProps?.includes("pos"), r.overrodeOwner]).toEqual(["owner", true, undefined]);
    // an owner-added or owner-deleted entity is all his
    expect(ownerHeld({ ...r, ownerProps: undefined, added: true })).toEqual(["*"]);
    expect(ownerConflicts({ ...r, ownerProps: ["*"] }, T0, { ...T0, yaw: 5 })).toEqual(["*"]);
  });
});

describe("edit records for any entity", () => {
  it("records a light's component change, by the agent, and clears it when undone", () => {
    const before = run(createScene("s"), build()).doc;
    const after = applyOps(before, [{ op: "set-component", id: "room--lamp", component: "light", data: { kind: "point", color: "#00ff00", intensity: 4, range: 8 } }], reg);
    const [edit] = entityEditsOf(before, after.doc, after.changedEntities);
    expect(edit!.kind).toEqual(["light", "transform"]);
    let file = ownerOverridesSchema.parse({ scene: "s", frame: "scene" });
    file = recordOwnerEdit(file, { item: edit!.entity, before: edit!.before, after: edit!.after, builder: "b", name: edit!.name, kind: edit!.kind }, "t1", "agent");
    const r = file.overrides[0]!;
    expect(r.by).toBe("agent");
    expect(r.reasons).toEqual(["edited"]);
    expect(Object.keys(r.set.components!)).toEqual(["light"]);
    expect(r.builder).toBe("b");
    // back to what the builder placed: the record goes
    file = recordOwnerEdit(file, { item: edit!.entity, before: edit!.after, after: edit!.before }, "t2", "owner");
    expect(file.overrides).toEqual([]);
  });

  it("keeps a tilt (not just yaw) through record and apply", () => {
    const q = [0.2588, 0, 0, 0.9659];
    const before = run(createScene("s"), build()).doc;
    const after = applyOps(before, [{ op: "set-component", id: "room--barrel-1", component: "transform", data: { position: [3, 0, 1], rotation: q, scale: [1, 2, 1] } }], reg);
    const [edit] = entityEditsOf(before, after.doc, after.changedEntities);
    const file = recordOwnerEdit(ownerOverridesSchema.parse({ scene: "s", frame: "scene" }), { item: edit!.entity, before: edit!.before, after: edit!.after, builder: "b" });
    expect(file.overrides[0]!.reasons).toEqual(["rotated", "scaled"]);
    const p = sync(before, build(), file);
    const doc = applyOps(before, p.ops, reg).doc;
    expect((doc.entities["room--barrel-1"]!.components["transform"] as { rotation: number[]; scale: number[] })).toMatchObject({ rotation: q, scale: [1, 2, 1] });
  });
});
