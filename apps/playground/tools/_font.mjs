export const GLYPH_W = 5;
export const GLYPH_H = 7;

/** Width in pixels of `text` at `scale`, with one blank column between glyphs. */
export function textWidth(text, scale) {
  return text.length * (GLYPH_W + 1) * scale - scale;
}

/**
 * Call `plot(x, y)` for every pixel of `text` drawn with its top-left at
 * (ox, oy). Unknown characters are skipped rather than drawn as a box.
 */
export function drawText(text, ox, oy, scale, plot) {
  let cx = ox;
  for (const ch of text.toUpperCase()) {
    const g = GLYPHS[ch];
    if (g) {
      for (let row = 0; row < GLYPH_H; row++)
        for (let col = 0; col < GLYPH_W; col++) {
          if (!(g[row] & (1 << (GLYPH_W - 1 - col)))) continue;
          for (let sy = 0; sy < scale; sy++)
            for (let sx = 0; sx < scale; sx++) plot(cx + col * scale + sx, oy + row * scale + sy);
        }
    }
    cx += (GLYPH_W + 1) * scale;
  }
}
